type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translate;
  errorMessage: (error: unknown, fallback: MessageKey) => string;
  codeMessage: (code: string | undefined, fallback: MessageKey) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

function initialLocale(): Locale {
  if (typeof window === "undefined") return "zh-CN";
  try {
    const saved = window.localStorage.getItem(localeStorageKey);
    if (saved === "zh-CN" || saved === "en") return saved;
  } catch {
    // Browser storage can be disabled.
  }
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale);
  const t = useCallback<Translate>((key, params) => {
    const template = messages[locale][key];
    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => {
      const value = params?.[name];
      return value === undefined ? match : String(value);
    });
  }, [locale]);

  const codeMessage = useCallback((code: string | undefined, fallback: MessageKey) => {
    const key = code ? errorKeys[code] : undefined;
    return t(key || fallback);
  }, [t]);

  const errorMessage = useCallback((error: unknown, fallback: MessageKey) => {
    return codeMessage(error instanceof ApiError ? error.code : undefined, fallback);
  }, [codeMessage]);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = t("app.title");
    try {
      window.localStorage.setItem(localeStorageKey, locale);
    } catch {
      // Browser storage can be disabled.
    }
  }, [locale, t]);

  const value = useMemo(() => ({ locale, setLocale, t, errorMessage, codeMessage }), [codeMessage, errorMessage, locale, t]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used within LocaleProvider");
  return value;
}
